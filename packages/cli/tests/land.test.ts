import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, test } from "vitest";
import { LAND_RECORD, parseLandArgs, runLand, type LandOptions } from "../src/commands/land.js";
import { makeTmpDir, type TmpRepo } from "./helpers.js";

// Real repositories, no mocks: a bare remote, the checkout the orchestrator lands in
// (`work`), and a builder clone that pushes ralph/* branches and moves the base the way
// other lands would. The gate is a script in the repo; it fails on a tracked RED file
// (RED_FULL for the full tier only) and, when the `moves` file asks, lands a commit on
// the base from the builder clone while it runs — the remote moving between the fetch
// and the push.

const BASE = "spec/1-x";

const MANIFEST = `schemaVersion: 1
issueTracker: github
testing:
  checkCommand: node gate.mjs fast
  unitCommand: node gate.mjs full
`;

const GATE = `import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const tier = process.argv[2] ?? "fast";
const moves = fileURLToPath(new URL("../moves", import.meta.url));
const left = existsSync(moves) ? Number(readFileSync(moves, "utf8")) : 0;
if (left > 0) {
  writeFileSync(moves, String(left - 1));
  const builder = fileURLToPath(new URL("../builder", import.meta.url));
  const git = (...args) => execFileSync("git", args, { cwd: builder, stdio: "ignore" });
  git("fetch", "-q", "origin");
  git("checkout", "-q", "-B", "mover", "origin/${BASE}");
  writeFileSync(builder + "/moved-" + left + ".txt", "moved\\n");
  git("add", "-A");
  git("commit", "-q", "-m", "elsewhere " + left);
  git("push", "-q", "origin", "mover:${BASE}");
}
if (existsSync("REWRITE")) writeFileSync("app.txt", "regenerated by the gate\\n");
if (existsSync("RED")) { console.log("gate " + tier + ": RED is present"); process.exit(1); }
if (tier === "full" && existsSync("RED_FULL")) { console.log("gate full: RED_FULL is present"); process.exit(1); }
console.log("gate " + tier + ": ok");
`;

interface Fixture {
  root: string;
  remote: string;
  work: string;
  builder: string;
}

let tmp: TmpRepo;
let f: Fixture;

function git(cwd: string, ...args: string[]): string {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function configure(cwd: string): void {
  git(cwd, "config", "user.email", "test@example.com");
  git(cwd, "config", "user.name", "Launchrail Test");
}

function write(cwd: string, path: string, content: string): void {
  writeFileSync(join(cwd, path), content, "utf8");
}

beforeEach(() => {
  tmp = makeTmpDir();
  const remote = join(tmp.root, "remote.git");
  const work = join(tmp.root, "work");
  const builder = join(tmp.root, "builder");
  execFileSync("git", ["init", "-q", "--bare", "-b", "master", remote]);
  execFileSync("git", ["clone", "-q", remote, work], { stdio: "ignore" });
  configure(work);
  write(work, ".launchrail.yml", MANIFEST);
  write(work, "gate.mjs", GATE);
  write(work, "app.txt", "line one\n");
  git(work, "add", "-A");
  git(work, "commit", "-q", "-m", "init");
  git(work, "push", "-q", "origin", "master");
  git(work, "checkout", "-q", "-b", BASE);
  git(work, "push", "-q", "-u", "origin", BASE);
  execFileSync("git", ["clone", "-q", remote, builder], { stdio: "ignore" });
  configure(builder);
  f = { root: tmp.root, remote, work, builder };
});
afterEach(() => tmp.cleanup());

/** A builder pushes `name` from the tip of `from` with these files; returns its tip. */
function pushBranch(name: string, files: Record<string, string>, from = BASE): string {
  git(f.builder, "fetch", "-q", "origin");
  git(f.builder, "checkout", "-q", "-B", name, `origin/${from}`);
  for (const [path, content] of Object.entries(files)) write(f.builder, path, content);
  git(f.builder, "add", "-A");
  git(f.builder, "commit", "-q", "-m", `work on ${name}`);
  git(f.builder, "push", "-q", "-f", "origin", name);
  return git(f.builder, "rev-parse", "HEAD");
}

/** Another land reaches the base: a commit pushed onto it from the builder clone. */
function advanceBase(files: Record<string, string>): string {
  git(f.builder, "fetch", "-q", "origin");
  git(f.builder, "checkout", "-q", "-B", "elsewhere", `origin/${BASE}`);
  for (const [path, content] of Object.entries(files)) write(f.builder, path, content);
  git(f.builder, "add", "-A");
  git(f.builder, "commit", "-q", "-m", "landed elsewhere");
  git(f.builder, "push", "-q", "origin", `elsewhere:${BASE}`);
  return git(f.builder, "rev-parse", "HEAD");
}

const remoteTip = (ref = BASE): string => git(f.remote, "rev-parse", ref);
const parents = (commit: string): string[] => git(f.remote, "rev-list", "--parents", "-n", "1", commit).split(" ").slice(1);
const land = (opts: Partial<LandOptions> & { branch: string }) => runLand({ cwd: f.work, base: BASE, ...opts });
const records = (): { status: string }[] =>
  readFileSync(join(f.work, LAND_RECORD), "utf8")
    .trim()
    .split("\n")
    .map((line) => JSON.parse(line) as { status: string });

describe("launchrail land", () => {
  test("lands a pushed branch: a merge commit on the remote base that keeps the branch's commits", () => {
    const before = remoteTip();
    const sha = pushBranch("ralph/12-feature", { "feature.txt": "new\n" });
    const { code, result } = land({ branch: "ralph/12-feature", issue: 12, title: "feat: add the feature" });

    expect(code).toBe(0);
    expect(result.status).toBe("landed");
    expect(result.mergeCommit).toBe(remoteTip());
    expect(parents(result.mergeCommit!)).toEqual([before, sha]);
    const message = git(f.remote, "log", "-1", "--format=%B", BASE);
    expect(message).toContain("feat: add the feature (#12)");
    expect(message).toContain("Closes #12");
    expect(message).toContain(`Landed from ralph/12-feature@${sha.slice(0, 7)} by launchrail land.`);
    expect(result.baseMoved).toBe(false);
    expect(result.branchSha).toBe(sha);
    expect(result.baseSha).toBe(before);
    expect(result.gate).toMatchObject({ tier: "fast", exitCode: 0, tail: [] });
    expect(readFileSync(join(f.work, result.gate!.log), "utf8")).toContain("gate fast: ok");
    // The checkout ends on the base at the landed tip, clean: the state dir ignores itself.
    expect(git(f.work, "rev-parse", "--abbrev-ref", "HEAD")).toBe(BASE);
    expect(git(f.work, "rev-parse", "HEAD")).toBe(result.mergeCommit);
    expect(git(f.work, "status", "--porcelain")).toBe("");
    expect(records().map((r) => r.status)).toEqual(["landed"]);
  });

  test("lands when the base moved under the branch, and says the base moved", () => {
    pushBranch("ralph/13-other", { "other.txt": "x\n" });
    const moved = advanceBase({ "unrelated.txt": "y\n" });
    const { result } = land({ branch: "ralph/13-other", issue: 13 });
    expect(result.status).toBe("landed");
    expect(result.baseMoved).toBe(true);
    expect(parents(remoteTip())[0]).toBe(moved);
  });

  test("a conflict leaves the base at the remote tip and names the files", () => {
    pushBranch("ralph/14-clash", { "app.txt": "from the branch\n" });
    const moved = advanceBase({ "app.txt": "from the base\n" });
    const { code, result } = land({ branch: "ralph/14-clash", issue: 14 });

    expect(code).toBe(1);
    expect(result.status).toBe("conflict");
    expect(result.conflicts).toEqual(["app.txt"]);
    expect(result.baseMoved).toBe(true);
    expect(remoteTip()).toBe(moved);
    expect(git(f.work, "rev-parse", "HEAD")).toBe(moved);
    expect(git(f.work, "status", "--porcelain")).toBe("");
  });

  test("a red gate pushes nothing, restores the base, and returns the failing lines", () => {
    const before = remoteTip();
    pushBranch("ralph/15-red", { RED: "x\n" });
    const { code, result } = land({ branch: "ralph/15-red", issue: 15 });

    expect(code).toBe(1);
    expect(result.status).toBe("gate-failed");
    expect(result.baseMoved).toBe(false);
    expect(result.gate?.exitCode).toBe(1);
    expect(result.gate?.tail.join("\n")).toContain("gate fast: RED is present");
    expect(remoteTip()).toBe(before);
    expect(git(f.work, "rev-parse", "HEAD")).toBe(before);
    expect(existsSync(join(f.work, "RED"))).toBe(false);
    expect(git(f.work, "status", "--porcelain")).toBe("");
  });

  test("--full gates with the whole contract; the fast tier alone would have passed", () => {
    pushBranch("ralph/16-full", { RED_FULL: "x\n" });
    const full = land({ branch: "ralph/16-full", full: true });
    expect(full.result.status).toBe("gate-failed");
    expect(full.result.gate).toMatchObject({ tier: "full", exitCode: 1 });
    const fast = land({ branch: "ralph/16-full" });
    expect(fast.result.status).toBe("landed");
  });

  test("refuses a dirty checkout and leaves the edit in place", () => {
    const before = remoteTip();
    pushBranch("ralph/17-any", { "any.txt": "x\n" });
    write(f.work, "app.txt", "an uncommitted edit\n");
    const { code, result } = land({ branch: "ralph/17-any" });
    expect(code).toBe(1);
    expect(result.status).toBe("failed");
    expect(result.summary).toContain("dirty checkout");
    expect(readFileSync(join(f.work, "app.txt"), "utf8")).toBe("an uncommitted edit\n");
    expect(remoteTip()).toBe(before);
  });

  test("untracked files do not block a land", () => {
    pushBranch("ralph/18-any", { "any.txt": "x\n" });
    write(f.work, "scratch.txt", "untracked\n");
    expect(land({ branch: "ralph/18-any" }).result.status).toBe("landed");
    expect(existsSync(join(f.work, "scratch.txt"))).toBe(true);
  });

  test("a local base with unpushed commits is refused, never pushed along", () => {
    const before = remoteTip();
    pushBranch("ralph/19-any", { "any.txt": "x\n" });
    write(f.work, "local.txt", "local only\n");
    git(f.work, "add", "-A");
    git(f.work, "commit", "-q", "-m", "local only");
    const { result } = land({ branch: "ralph/19-any" });
    expect(result.status).toBe("failed");
    expect(result.summary).toContain("not on origin");
    expect(remoteTip()).toBe(before);
  });

  test("landing the same branch twice reports already-landed with the merge that landed it", () => {
    pushBranch("ralph/20-once", { "once.txt": "x\n" });
    const first = land({ branch: "ralph/20-once", issue: 20 });
    const again = land({ branch: "ralph/20-once", issue: 20 });
    expect(again.code).toBe(0);
    expect(again.result.status).toBe("already-landed");
    expect(again.result.mergeCommit).toBe(first.result.mergeCommit);
    expect(remoteTip()).toBe(first.result.mergeCommit);
  });

  test("refuses the remote's default branch without --trunk, and lands there with it", () => {
    const before = remoteTip("master");
    pushBranch("ralph/21-hotfix", { "hotfix.txt": "x\n" }, "master");
    const refused = land({ branch: "ralph/21-hotfix", base: "master" });
    expect(refused.result.status).toBe("failed");
    expect(refused.result.summary).toContain("default branch");
    expect(remoteTip("master")).toBe(before);
    const trunk = land({ branch: "ralph/21-hotfix", base: "master", trunk: true });
    expect(trunk.result.status).toBe("landed");
    expect(remoteTip("master")).toBe(trunk.result.mergeCommit);
  });

  test("a remote that moved during the gate is merged again once and lands on the new tip", () => {
    const sha = pushBranch("ralph/22-race", { "race.txt": "x\n" });
    write(f.root, "moves", "1");
    const { result } = land({ branch: "ralph/22-race" });
    expect(result.status).toBe("landed");
    const [first, second] = parents(remoteTip());
    expect(git(f.remote, "log", "-1", "--format=%s", first!)).toBe("elsewhere 1");
    expect(second).toBe(sha);
    expect(readFileSync(join(f.work, result.gate!.log), "utf8").match(/gate fast: ok/g)).toHaveLength(2);
  });

  test("a remote that keeps moving is stale: the base is restored to its tip and nothing is pushed", () => {
    pushBranch("ralph/23-race", { "race.txt": "x\n" });
    write(f.root, "moves", "2");
    const { code, result } = land({ branch: "ralph/23-race" });
    expect(code).toBe(1);
    expect(result.status).toBe("stale");
    expect(git(f.remote, "log", "-1", "--format=%s", BASE)).toBe("elsewhere 1");
    expect(git(f.work, "rev-parse", "HEAD")).toBe(remoteTip());
    expect(git(f.work, "status", "--porcelain")).toBe("");
  });

  test("--dry-run predicts a clean merge or a conflict and writes nothing", () => {
    const before = remoteTip();
    pushBranch("ralph/24-clean", { "clean.txt": "x\n" });
    pushBranch("ralph/25-clash", { "app.txt": "from the branch\n" });
    git(f.work, "checkout", "-q", "master");
    const clean = land({ branch: "ralph/24-clean", dryRun: true });
    expect(clean.code).toBe(0);
    expect(clean.result.status).toBe("would-land");
    const moved = advanceBase({ "app.txt": "from the base\n" });
    const clash = land({ branch: "ralph/25-clash", dryRun: true });
    expect(clash.result.status).toBe("would-conflict");
    expect(clash.result.conflicts).toEqual(["app.txt"]);
    // No checkout, no merge, no push, no record.
    expect(git(f.work, "rev-parse", "--abbrev-ref", "HEAD")).toBe("master");
    expect(remoteTip()).toBe(moved);
    expect(remoteTip()).not.toBe(before);
    expect(existsSync(join(f.work, ".launchrail/state"))).toBe(false);
  });

  test("one land at a time: a live holder's lock refuses, a dead holder's lock is taken over", () => {
    const before = remoteTip();
    pushBranch("ralph/26-lock", { "lock.txt": "x\n" });
    const lock = join(f.work, ".git", "launchrail-land.lock");
    writeFileSync(lock, JSON.stringify({ pid: process.pid, branch: "ralph/9-other", since: "earlier" }));
    const busy = land({ branch: "ralph/26-lock" });
    expect(busy.result.status).toBe("failed");
    expect(busy.result.summary).toContain("another land is running");
    expect(remoteTip()).toBe(before);

    writeFileSync(lock, JSON.stringify({ pid: 2147483646, branch: "ralph/9-other", since: "earlier" }));
    expect(land({ branch: "ralph/26-lock" }).result.status).toBe("landed");
    expect(existsSync(lock)).toBe(false);
  });

  test("the lock is taken before anything else: a land mid-merge is reported as running, not as a dirty tree", () => {
    pushBranch("ralph/34-lock", { "lock.txt": "x\n" });
    writeFileSync(join(f.work, ".git", "launchrail-land.lock"), JSON.stringify({ pid: process.pid, branch: "ralph/9-other", since: "earlier" }));
    write(f.work, "app.txt", "the other land's half-merged tree\n");
    const { result } = land({ branch: "ralph/34-lock" });
    expect(result.summary).toContain("another land is running");
  });

  test("a base that moved with dependency changes gets an install before the gate judges it", () => {
    pushBranch("ralph/35-plain", { "plain.txt": "x\n" });
    advanceBase({ "package.json": '{ "name": "app" }\n' });
    const install = `node -e "require('fs').mkdirSync('node_modules', { recursive: true }); require('fs').writeFileSync('installed.txt', 'yes')"`;
    const { result } = land({ branch: "ralph/35-plain", install });
    // Without the catch-up install the gate would fail on "dependencies are not installed".
    expect(result.status).toBe("landed");
    expect(result.installed).toBe(install);
    expect(readFileSync(join(f.work, "installed.txt"), "utf8")).toBe("yes");
  });

  test("dependency changes run the install command before the gate", () => {
    pushBranch("ralph/27-deps", { "package.json": '{ "name": "app" }\n' });
    const install = `node -e "require('fs').mkdirSync('node_modules', { recursive: true }); require('fs').writeFileSync('installed.txt', 'yes')"`;
    const { result } = land({ branch: "ralph/27-deps", install });
    expect(result.status).toBe("landed");
    expect(result.installed).toBe(install);
    expect(readFileSync(join(f.work, "installed.txt"), "utf8")).toBe("yes");
  });

  test("a failing install is a red gate: nothing pushed, and the tail says what failed", () => {
    const before = remoteTip();
    pushBranch("ralph/28-deps", { "package.json": '{ "name": "app" }\n' });
    const { result } = land({ branch: "ralph/28-deps", install: `node -e "console.log('lockfile out of date'); process.exit(4)"` });
    expect(result.status).toBe("gate-failed");
    expect(result.summary).toContain("install");
    expect(result.gate?.tail.join("\n")).toContain("lockfile out of date");
    expect(remoteTip()).toBe(before);
  });

  test("a gate that rewrites tracked files is cleaned up after the land, so the next land is not refused", () => {
    pushBranch("ralph/32-rewrites", { REWRITE: "x\n" });
    const first = land({ branch: "ralph/32-rewrites" });
    expect(first.result.status).toBe("landed");
    expect(first.result.summary).toContain("rewrote 1 tracked file");
    expect(git(f.work, "status", "--porcelain")).toBe("");
    expect(readFileSync(join(f.work, "app.txt"), "utf8")).toBe("line one\n");
    pushBranch("ralph/33-next", { "next.txt": "x\n" });
    expect(land({ branch: "ralph/33-next" }).result.status).toBe("landed");
  });

  test("--expect refuses a branch that moved since the hand-off", () => {
    const handedOff = pushBranch("ralph/29-moving", { "a.txt": "x\n" });
    git(f.builder, "commit", "-q", "--allow-empty", "-m", "still pushing");
    git(f.builder, "push", "-q", "origin", "ralph/29-moving");
    const { result } = land({ branch: "ralph/29-moving", expect: handedOff.slice(0, 7) });
    expect(result.status).toBe("failed");
    expect(result.summary).toContain("moved since the hand-off");
  });

  test("a branch that is not on the remote fails by name", () => {
    const { result } = land({ branch: "ralph/30-missing" });
    expect(result.status).toBe("failed");
    expect(result.summary).toContain("ralph/30-missing is not on origin");
  });

  test("outside a Launchrail project it refuses before touching git, and records nothing", () => {
    const plain = join(f.root, "plain");
    execFileSync("git", ["clone", "-q", f.remote, plain], { stdio: "ignore" });
    git(plain, "rm", "-q", ".launchrail.yml");
    const { result } = runLand({ cwd: plain, branch: "ralph/31-any", base: BASE });
    expect(result.status).toBe("failed");
    expect(result.summary).toContain(".launchrail.yml");
    expect(existsSync(join(plain, ".launchrail/state"))).toBe(false);
  });
});

describe("launchrail land arguments", () => {
  test("parses a full invocation", () => {
    const parsed = parseLandArgs([
      "ralph/12-feature", "--base", BASE, "--issue", "#12", "--title", "feat: add it", "--expect", "abc1234", "--full", "--json",
    ]);
    expect(parsed).toEqual({
      options: {
        branch: "ralph/12-feature", base: BASE, remote: "origin", issue: 12, title: "feat: add it", expect: "abc1234",
        install: null, full: true, trunk: false, dryRun: false,
      },
      json: true,
    });
  });

  test("refuses what it would otherwise have to guess", () => {
    expect(parseLandArgs(["--base", BASE])).toEqual({ error: "name exactly one branch to land" });
    expect(parseLandArgs(["ralph/1-x"])).toMatchObject({ error: expect.stringContaining("--base is required") });
    expect(parseLandArgs(["ralph/1-x", "--base", "ralph/1-x"])).toMatchObject({ error: expect.stringContaining("same") });
    expect(parseLandArgs(["ralph/1-x", "--base", BASE, "--issue", "twelve"])).toMatchObject({ error: expect.stringContaining("--issue") });
    expect(parseLandArgs(["ralph/1-x", "--base", BASE, "--expect", "main"])).toMatchObject({ error: expect.stringContaining("--expect") });
    expect(parseLandArgs(["ralph/1-x", "--base", BASE, "--squash"])).toEqual({ error: "unknown option --squash" });
    expect(parseLandArgs(["ralph/1-x", "--base"])).toEqual({ error: "--base needs a value" });
  });
});
